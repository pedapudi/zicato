// variants/J/views/report.js — NEW VIEW: ACM-style epoch publication.
//
// The convergence brief's second new screen (E lacked it). The epoch's
// analyzer publication, rendered Tufte/editorial from `analysis_md`. We reuse
// the v2 report APPROACH — parse the section markers
// (`<!-- EYEBROW -->`, `<!-- META -->`, `## Abstract`, the body sections,
// `<!-- FIGURE:NAME -->`, `<!-- CALLOUT:... -->`) — but render to typeset DOM
// (NOT an iframe), so the paper reads inside the Console chrome and we can
// embed LIVE Tufte figures inline where the markdown places a figure marker.
//
// Bind: /api/epoch/{epoch_id}/analysis → { analysis_md }. (analysis.html may
// 404 — we use analysis_md, the honest source of truth.)
//
// Cold deep-link safe: #/J/report/<epochId> fetches its own analysis +
// lineage + matchup grid and paints loading → content, never a blank panel.

import { el } from '../../../core/dom.js';
import { state } from '../../../core/state.js';
import * as D from '../data.js';
import * as svg from '../svg.js';
import { gatedSwap, empty, normaliseDecision } from '../ui.js';

export async function render(host, ctx, params) {
  if (!host.firstChild) host.appendChild(el('p', { class: 'dj-empty', text: 'Reading epoch publication…' }));

  // Resolve the epoch id from the route, else the live epoch.
  let epochId = (params && params.epochId) || null;
  if (!epochId) {
    const ep = await D.epoch();
    epochId = (ep && ep.epoch_id) || (state.epochDef && state.epochDef.epoch_id) || null;
  }
  if (!epochId) {
    gatedSwap(host, 'no-epoch', () => [el('h1', { class: 'dj-h1', text: 'Epoch publication' }), empty('No epoch selected.')]);
    return;
  }

  // Fetch the analysis + the live figure data (lineage, score traj, one
  // matchup grid) so figures embed even on a cold deep-link.
  const [analysis, lin, traj, bracket] = await Promise.all([
    D.analysis(epochId), D.lineage(), D.scoreTrajectory(), D.bracket(),
  ]);
  const md = (analysis && typeof analysis.analysis_md === 'string') ? analysis.analysis_md : '';

  // figure substrate
  const gens = (lin && Array.isArray(lin.generations) && lin.generations.length)
    ? lin.generations.map((g) => ({ id: g.generation_id, parent: g.parent_generation_id || null, promoted: !!g.promoted }))
    : [];
  const scalarByGen = new Map();
  if (traj && Array.isArray(traj.points)) for (const p of traj.points) if (svg.isNum(p.scalar)) scalarByGen.set(p.generation_id, p.scalar);
  const matchups = (bracket && Array.isArray(bracket.matchups)) ? bracket.matchups : [];

  // a paired grid for the first decided matchup (figure: matchup slopegraph).
  let firstGrid = null, firstMatchup = null;
  if (matchups.length && matchups[0].champion && matchups[0].challenger) {
    firstMatchup = matchups[0];
    firstGrid = await D.matchupGrid(epochId, firstMatchup.champion, firstMatchup.challenger);
  }

  const digest = JSON.stringify({
    epochId, mdLen: md.length,
    gens: gens.map((g) => [g.id, g.parent, g.promoted, scalarByGen.has(g.id) ? scalarByGen.get(g.id).toFixed(3) : null]),
    grid: firstGrid && Array.isArray(firstGrid.entry_grid) ? firstGrid.entry_grid.map((r) => [r.entry_id, r.parent_drift_loss, r.child_drift_loss, r.verdict]) : null,
  });

  const figures = { gens, scalarByGen, firstGrid, firstMatchup, ctx };

  gatedSwap(host, digest, () => {
    if (!md.trim()) {
      return [
        el('div', { class: 'dj-pagehead' }, [el('h1', { class: 'dj-h1', text: 'Epoch publication' })]),
        el('div', { class: 'dj-panel' }, [
          empty('No analysis report built yet for ' + epochId + '.'),
          el('p', { class: 'dj-faint', style: 'font-size:12px;', text: 'It is generated by the analyzer — run `zicato epoch analyze --epoch ' + epochId + '` to build it.' }),
        ]),
      ];
    }
    const paper = el('article', { class: 'dj-paper' });
    renderPaper(paper, md, figures);
    return [paper];
  });
}

// Parse analysis_md into typeset DOM. Markers (matching the analyzer):
//   <!-- EYEBROW -->            the next paragraph is the masthead eyebrow.
//   <!-- META -->               the next paragraph is the byline / meta line.
//   ## Abstract                 the abstract section (set apart).
//   <!-- FIGURE:NAME -->        embed a live figure (lineage / matchup / drift).
//   <!-- CALLOUT:LABEL -->      the next paragraph is a callout.
//   # / ## / ### …              headings (## opens a section).
//   - / *                       bullet list. ``` fenced code.
function renderPaper(root, md, figures) {
  const lines = String(md).replace(/\r\n/g, '\n').split('\n');
  let i = 0;
  let para = [];
  let list = null;
  let pendingEyebrow = false;
  let pendingMeta = false;
  let pendingCallout = null;
  let abstractMode = false;

  const flushPara = () => {
    if (!para.length) return;
    const text = para.join(' ');
    if (pendingEyebrow) { root.appendChild(el('div', { class: 'dj-paper-eyebrow', text }, null)); pendingEyebrow = false; }
    else if (pendingMeta) { root.appendChild(el('div', { class: 'dj-paper-meta' }, inline(text))); pendingMeta = false; }
    else if (pendingCallout != null) {
      root.appendChild(el('aside', { class: 'dj-paper-callout' }, [
        pendingCallout ? el('span', { class: 'dj-paper-callout-label', text: pendingCallout }) : null,
        el('p', null, inline(text)),
      ].filter(Boolean)));
      pendingCallout = null;
    } else {
      root.appendChild(el('p', { class: abstractMode ? 'dj-paper-abstract-p' : 'dj-paper-p' }, inline(text)));
    }
    para = [];
  };
  const flushList = () => { if (list) { root.appendChild(list); list = null; } };

  while (i < lines.length) {
    const line = lines[i];
    const stripped = line.trim();

    // markers
    if (stripped === '<!-- EYEBROW -->') { flushPara(); flushList(); pendingEyebrow = true; i++; continue; }
    if (stripped === '<!-- META -->') { flushPara(); flushList(); pendingMeta = true; i++; continue; }
    const figM = /^<!--\s*FIGURE:([A-Za-z0-9_-]+)\s*-->$/.exec(stripped);
    if (figM) { flushPara(); flushList(); root.appendChild(figureFor(figM[1], figures)); i++; continue; }
    const calloutM = /^<!--\s*CALLOUT:([^>]*?)\s*-->$/.exec(stripped);
    if (calloutM) { flushPara(); flushList(); pendingCallout = (calloutM[1] || '').trim(); i++; continue; }
    if (/^<!--/.test(stripped)) { i++; continue; } // any other comment marker

    // fenced code
    if (/^```/.test(stripped)) {
      flushPara(); flushList();
      const buf = [];
      i++;
      while (i < lines.length && !/^```/.test(lines[i].trim())) { buf.push(lines[i]); i++; }
      i++;
      root.appendChild(el('pre', { class: 'dj-paper-pre' }, [el('code', { text: buf.join('\n') })]));
      continue;
    }

    const heading = /^(#{1,6})\s+(.*)$/.exec(line);
    if (heading) {
      flushPara(); flushList();
      const lvl = heading[1].length;
      const content = heading[2].trim();
      if (lvl === 1) {
        root.appendChild(el('h1', { class: 'dj-paper-title' }, inline(content)));
        abstractMode = false;
      } else if (lvl === 2 && content.toLowerCase() === 'abstract') {
        root.appendChild(el('h2', { class: 'dj-paper-h2 dj-paper-abstract-h', text: 'Abstract' }));
        abstractMode = true;
      } else {
        root.appendChild(el('h' + Math.min(4, lvl), { class: 'dj-paper-h' + Math.min(4, lvl) }, inline(content)));
        abstractMode = false;
      }
      i++; continue;
    }

    const bullet = /^\s*[-*]\s+(.*)$/.exec(line);
    if (bullet) {
      flushPara();
      if (!list) list = el('ul', { class: 'dj-paper-ul' });
      list.appendChild(el('li', null, inline(bullet[1])));
      i++; continue;
    }

    if (stripped === '') { flushPara(); flushList(); i++; continue; }
    flushList();
    para.push(stripped);
    i++;
  }
  flushPara(); flushList();
}

// A live Tufte figure for a FIGURE marker. Unknown names degrade to a quiet
// caption so the paper never breaks on an unexpected marker.
function figureFor(name, figures) {
  const key = String(name).toLowerCase();
  const { gens, scalarByGen, firstGrid, firstMatchup, ctx } = figures;
  const fig = el('figure', { class: 'dj-paper-fig' });

  if ((key.includes('lineage') || key.includes('bump')) && gens.length) {
    const bumpNodes = gens.map((g, i) => ({ id: g.id, x: i, promoted: g.promoted, scalar: scalarByGen.get(g.id), parent: g.parent }));
    if (!bumpNodes.some((n) => n.promoted)) bumpNodes[0].promoted = true;
    fig.appendChild(svg.bumps({ width: 640, height: 160, nodes: bumpNodes, onClick: (n) => ctx.navigate('candidate', { gen: n.id }) }));
    fig.appendChild(el('figcaption', { class: 'dj-paper-figcap', text: 'Figure · lineage bumps — champion spine vs rejected challengers (click a node → candidate).' }));
    return fig;
  }
  if ((key.includes('matchup') || key.includes('slope') || key.includes('duel')) && firstGrid && Array.isArray(firstGrid.entry_grid)) {
    const series = firstGrid.entry_grid
      .filter((r) => svg.isNum(r.parent_drift_loss) || svg.isNum(r.child_drift_loss))
      .map((r) => ({ label: r.entry_id, id: r.entry_id, a: svg.isNum(r.parent_drift_loss) ? r.parent_drift_loss : NaN, b: svg.isNum(r.child_drift_loss) ? r.child_drift_loss : NaN, verdict: r.verdict }));
    fig.appendChild(svg.pairedSlopegraph({
      width: 520, height: Math.max(200, 50 + series.length * 26),
      left: { title: `champion ${firstMatchup.champion}` }, right: { title: `challenger ${firstMatchup.challenger}` },
      labelGap: 150, goodDirection: 'down', series,
      onClick: (s) => ctx.navigate('run', { gen: firstMatchup.challenger, entry: s.id }),
    }));
    fig.appendChild(el('figcaption', { class: 'dj-paper-figcap', text: `Figure · paired per-board duel ${firstMatchup.champion} → ${firstMatchup.challenger} (de-collided slopegraph; click a line → run).` }));
    return fig;
  }
  if ((key.includes('drift') || key.includes('heatmap')) && firstGrid && Array.isArray(firstGrid.entry_grid)) {
    const rows = firstGrid.entry_grid.map((r) => ({ id: r.entry_id, label: r.entry_id }));
    const cols = [{ id: 'champion', label: firstMatchup.champion }, { id: 'challenger', label: firstMatchup.challenger }];
    const lossLookup = new Map();
    for (const r of firstGrid.entry_grid) {
      if (svg.isNum(r.parent_drift_loss)) lossLookup.set(r.entry_id + '|champion', r.parent_drift_loss);
      if (svg.isNum(r.child_drift_loss)) lossLookup.set(r.entry_id + '|challenger', r.child_drift_loss);
    }
    fig.appendChild(svg.heatmap({ rows, cols, value: (rid, cid) => (lossLookup.has(rid + '|' + cid) ? lossLookup.get(rid + '|' + cid) : null) }));
    fig.appendChild(el('figcaption', { class: 'dj-paper-figcap', text: 'Figure · per-board drift loss heatmap (champion vs challenger; denser ink = more drift).' }));
    return fig;
  }
  // unknown / no data — a quiet placeholder caption.
  fig.appendChild(el('figcaption', { class: 'dj-paper-figcap dj-faint', text: 'Figure · ' + name + ' (no live data available).' }));
  return fig;
}

function inline(s) {
  const out = [];
  const re = /(`[^`]+`|\*\*[^*]+\*\*|\*[^*]+\*)/g;
  let last = 0; let m;
  while ((m = re.exec(s)) !== null) {
    if (m.index > last) out.push(s.slice(last, m.index));
    const tok = m[0];
    if (tok.startsWith('`')) out.push(el('code', { class: 'dj-paper-code', text: tok.slice(1, -1) }));
    else if (tok.startsWith('**')) out.push(el('strong', { text: tok.slice(2, -2) }));
    else out.push(el('em', { text: tok.slice(1, -1) }));
    last = m.index + tok.length;
  }
  if (last < s.length) out.push(s.slice(last));
  return out.length ? out : [s];
}
