//! A small, dependency-free SHA-256.
//!
//! The integrity-notary cluster hash-chains its audit ledger so a record
//! cannot be altered or dropped without breaking the chain. That needs a
//! collision-resistant digest, but the supervisor pins every dependency to
//! an exact version and avoids pulling new crates lightly — so rather than
//! add a `sha2`/`digest` dependency for one call site, this module carries
//! a compact, self-contained implementation of FIPS 180-4 SHA-256.
//!
//! It is deliberately tiny and not performance-tuned: the ledger appends at
//! human timescale (a handful of records per tournament), so a
//! straightforward implementation is more than fast enough. The output is
//! verified against the published NIST test vectors in the unit tests.

